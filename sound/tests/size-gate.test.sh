#!/usr/bin/env bash
# Runs the size gate against throwaway repos, one case per behaviour it must keep.
set -euo pipefail
gate=$(cd "$(dirname "$0")/../corpus/placement" && pwd)/file-stays-under-a-size-cap.gate
fails=0

big() { awk -v n="$1" 'BEGIN { for (i = 0; i < n; i++) print "a" }'; }

repo() {
  cd "$(mktemp -d)"
  git init -q && git config user.email t@t && git config user.name t
  git commit -q --allow-empty -m root
}

expect() { # expect <block|pass> <name>
  local got=pass
  /bin/bash "$gate" 2>/tmp/size-gate.err || got=block
  if [ "$got" = "$1" ]; then echo "ok   $2"; else echo "FAIL $2 (got $got)"; cat /tmp/size-gate.err; fails=$((fails + 1)); fi
}

repo; big 1000 >a.ts; git add a.ts; expect pass 'new file at the cap'
repo; big 1001 >a.ts; git add a.ts; expect block 'new file over the cap'
grep -q 'a.ts  1001 lines, new file' /tmp/size-gate.err && echo 'ok   message names the file' || { echo 'FAIL message'; fails=$((fails + 1)); }
repo; big 900 >a.ts; git add a.ts; git commit -qm a; big 1100 >a.ts; git add a.ts; expect block 'file grows past the cap'
repo; big 1500 >a.ts; git add a.ts; git commit -qm a; big 1600 >a.ts; git add a.ts; expect block 'old file over the cap grows'
repo; big 1500 >a.ts; git add a.ts; git commit -qm a; big 1400 >a.ts; git add a.ts; expect pass 'old file over the cap shrinks'
repo; big 1500 >a.ts; git add a.ts; git commit -qm a; git mv a.ts b.ts; expect pass 'old file over the cap is renamed'
repo; big 1500 >a.ts; git add a.ts; git commit -qm a; cp a.ts b.ts; git add b.ts; expect block 'old file over the cap is copied'
repo; big 1500 >pnpm-lock.yaml; git add .; expect pass 'known lock file'
repo; big 1500 >tool.lock; git add .; expect pass 'unknown .lock file'
repo; mkdir -p x/node_modules; big 1500 >x/node_modules/m.js; git add -f .; expect pass 'vendored path'
repo; echo 'gen.ts linguist-generated' >.gitattributes; big 1500 >gen.ts; git add .; expect pass 'linguist-generated attribute'
repo; { echo '// @generated'; big 1500; } >g.ts; git add .; expect pass '@generated header'
repo; { echo '// Code generated by protoc. DO NOT EDIT.'; big 1500; } >g.go; git add .; expect pass 'Go generated header'
repo; head -c 60000 /dev/urandom >img.png; git add .; expect pass 'binary file'
repo; big 1500 >'sp ace.ts'; git add .; expect block 'path with a space'

[ "$fails" -eq 0 ] && echo 'all passed' || { echo "$fails failed"; exit 1; }
